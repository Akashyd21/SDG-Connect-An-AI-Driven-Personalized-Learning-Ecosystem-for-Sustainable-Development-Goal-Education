create extension if not exists vector;

create table if not exists public.activities (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null,
  sdgs smallint[] not null,
  steps jsonb not null,
  difficulty text not null check (difficulty in ('beginner', 'intermediate', 'advanced')),
  hours numeric not null check (hours > 0 and hours <= 40),
  why_it_fits text not null,
  department text not null,
  source text not null default 'catalog' check (source in ('catalog', 'ai_generated')),
  approval_status text not null default 'approved' check (approval_status in ('pending', 'approved', 'rejected')),
  requested_by uuid references auth.users(id),
  reviewer_note text,
  embedding vector(1024),
  created_at timestamptz not null default now()
);

create table if not exists public.activity_feedback (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id),
  activity_id uuid not null references public.activities(id),
  event text not null check (event in ('started', 'completed', 'skipped')),
  rating smallint check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);

create index if not exists activities_embedding_idx on public.activities
using ivfflat (embedding vector_cosine_ops) with (lists = 100);

create or replace function public.match_activities(
  query_embedding vector(1024), wanted_sdgs smallint[], wanted_department text,
  wanted_difficulty text, max_hours numeric, result_limit integer
)
returns table (
  id uuid, title text, description text, sdgs smallint[], steps jsonb,
  difficulty text, hours numeric, why_it_fits text, department text,
  source text, approval_status text, score float
)
language sql stable
as $$
  select a.id, a.title, a.description, a.sdgs, a.steps, a.difficulty, a.hours,
    a.why_it_fits, a.department, a.source, a.approval_status,
    (1 - (a.embedding <=> query_embedding))::float as score
  from public.activities a
  where a.approval_status = 'approved'
    and a.hours <= max_hours
    and (a.department = wanted_department or a.department = 'All Departments')
    and a.sdgs && wanted_sdgs
  order by
    case when a.department = wanted_department then 0 else 1 end,
    case when a.difficulty = wanted_difficulty then 0 else 1 end,
    a.embedding <=> query_embedding
  limit result_limit;
$$;

alter table public.activities enable row level security;
alter table public.activity_feedback enable row level security;

create policy "approved activities are readable"
on public.activities for select using (approval_status = 'approved');

create policy "students can submit own feedback"
on public.activity_feedback for insert with check (auth.uid() = student_id);
