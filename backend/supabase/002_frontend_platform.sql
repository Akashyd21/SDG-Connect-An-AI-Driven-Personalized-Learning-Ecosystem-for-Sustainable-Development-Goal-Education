-- Profiles and student/faculty activity data used by the existing frontend.
-- Run after 001_activity_recommendations.sql.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('student', 'faculty')),
  name text not null,
  usn text unique,
  department text not null,
  phone text,
  email text,
  skills text[] not null default '{}',
  interests text[] not null default '{}',
  designation text,
  points integer not null default 100,
  tasks_completed_count integer not null default 0,
  ongoing_tasks_count integer not null default 0,
  avatar text,
  sdg_coverage jsonb not null default '{}'::jsonb,
  badges text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ongoing_tasks (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  activity_id uuid not null references public.activities(id) on delete cascade,
  assigned_at date not null default current_date,
  status text not null default 'in-progress',
  current_milestone_index smallint not null default 1,
  progress_pct numeric not null default 0,
  assigned_by text not null default 'ai_agent',
  ai_match_rationale text,
  unique(student_id, activity_id)
);

create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  activity_id uuid not null references public.activities(id) on delete cascade,
  task_title text not null,
  task_type text not null default 'field_activity',
  milestone_index smallint not null default 1,
  impact_summary text,
  location text,
  image_url text,
  github_repo_url text,
  colab_notebook_url text,
  training_loss_plot_url text,
  model_metrics_summary jsonb not null default '{}'::jsonb,
  live_demo_url text,
  verification jsonb not null default '{}'::jsonb,
  points_awarded integer not null default 0,
  submitted_at timestamptz not null default now()
);

create table if not exists public.activity_feedback (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  activity_id uuid not null references public.activities(id) on delete cascade,
  event text not null check (event in ('started', 'completed', 'skipped')),
  rating smallint check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_attempts (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  quiz_topic_id text not null,
  score integer not null default 0,
  total_questions integer not null default 0,
  answers jsonb not null default '{}'::jsonb,
  completed_at timestamptz not null default now()
);

alter table public.quiz_attempts
  add column if not exists points_awarded integer not null default 0;

create table if not exists public.game_scores (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  game_id text not null,
  score integer not null default 0,
  played_at timestamptz not null default now(),
  unique(student_id, game_id)
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  message text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists profiles_role_department_idx on public.profiles(role, department);
create index if not exists ongoing_tasks_student_idx on public.ongoing_tasks(student_id);
create index if not exists submissions_student_idx on public.submissions(student_id, submitted_at desc);
create index if not exists feedback_activity_idx on public.activity_feedback(activity_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.ongoing_tasks enable row level security;
alter table public.submissions enable row level security;
alter table public.activity_feedback enable row level security;
alter table public.quiz_attempts enable row level security;
alter table public.game_scores enable row level security;
alter table public.notifications enable row level security;

