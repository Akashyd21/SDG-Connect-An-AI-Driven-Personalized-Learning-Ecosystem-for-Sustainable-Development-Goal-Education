create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles
for each row execute function public.set_updated_at();

-- Create the public profile automatically when Supabase Auth creates a user.
-- This works even when email confirmation is enabled.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (
    id, role, name, usn, department, phone, email, skills, interests, designation
  ) values (
    new.id,
    coalesce(new.raw_user_meta_data->>'role', 'student'),
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    nullif(new.raw_user_meta_data->>'usn', ''),
    coalesce(new.raw_user_meta_data->>'department', 'All Departments'),
    new.raw_user_meta_data->>'phone',
    new.email,
    coalesce(array(select jsonb_array_elements_text(new.raw_user_meta_data->'skills')), '{}'),
    coalesce(array(select jsonb_array_elements_text(new.raw_user_meta_data->'interests')), '{}'),
    new.raw_user_meta_data->>'designation'
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

