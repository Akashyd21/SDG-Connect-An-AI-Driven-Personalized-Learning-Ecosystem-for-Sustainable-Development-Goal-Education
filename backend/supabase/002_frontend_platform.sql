-- The login form accepts USN as well as email. This narrowly scoped lookup lets
-- Supabase Auth receive the corresponding email without exposing profile rows.
create or replace function public.lookup_student_email(input_usn text)
returns text
language sql
security definer set search_path = public
as $$
  select email from public.profiles
  where role = 'student' and upper(usn) = upper(input_usn)
  limit 1;
$$;

grant execute on function public.lookup_student_email(text) to anon, authenticated;
